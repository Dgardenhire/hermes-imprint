"""The starter library: original kits, plus one public-domain design system for demos.

Each original kit was worked out the subject-led way, before any color was picked: who reads it, what
they need to do, and the one device only that subject has. They differ on purpose in layout family,
type pairing, ground, color share and voice, so two kits side by side never read as one page recolored.
None of them imitates a real organization, and none carries a logo; the logo slot belongs to the user.

Four kits (Payments Violet, Midnight Indigo, Poster Block, Parchment Ink) adapt the color and type values of
packages in Open Design (Apache-2.0; its catalog credits MIT upstreams). They carry neutral, descriptive names,
no logo or mark, and no claim to come from anyone. Where a package named a licensed typeface, the kit uses a
bundled OFL font marked ``stands_in``, and the colophon says it stands in for a licensed one. See NOTICE.

The US Web Design System kit follows (designsystem.digital.gov). USWDS is in the public
domain (GSA's work is CC0; its fonts are OFL). It carries no logo, no seal and no government banner text,
and documents made with it do not claim to come from any agency.

Fields are documented in kits.py. Colors are listed in role order; ``kits.palette`` measures each one
against the paper and decides what it may do.
"""

